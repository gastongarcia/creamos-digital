"""Generates the voice-over from the on-screen captions with Piper TTS.

usage: python3 narrate.py VOICE.onnx [SPEAKER]
Reads lines.json (from `node render.mjs lines`), writes narr/<scene>_<line>.wav
and narration.js with each line's spoken length, which index.html uses to
stretch its timeline so nothing moves on before the voice has finished.
"""
import json
import os
import re
import subprocess
import sys
import wave

HERE = os.path.dirname(os.path.abspath(__file__))

SPOKEN = [
    (r"\*", ""),
    (r"\(S\)|\(OH\)|\(MB\)|\(OPP\)|\(L\)", ""),
    (r"9 × 9 m", "9 by 9 metre"),
    (r"(\d) m line", r"\1 metre line"),
    (r"OH left, MB middle, S and OPP right", "outside hitters left, middles in the middle, setter and opposite right"),
    (r"\bIN\b", "in"),
    (r"\bOUT\b", "out"),
    (r"\bSET\b", "set"),
    (r"\bDIG\b", "dig"),
    (r" \+ ", " plus "),
    (r"(\d+(?:\.\d+)?) m\b", r"\1 metres"),
    (r"(\d+) cm\b", r"\1 centimetres"),
    (r"S↔OPP, OH↔OH, MB↔MB", "setter and opposite, outside and outside, middle and middle"),
    (r"(\d)→(\d)", r"\1 to \2"),
    (r"\b24–24\b", "24 all"),
    (r"\b1–1\b", "1 all"),
    (r"\b2–2\b", "2 all"),
    (r"(\d)–(\d)", r"\1 to \2"),
    (r"\bMB1\b", "middle blocker one"),
    (r"\bMB2\b", "middle blocker two"),
    (r"\bOH1\b", "outside hitter one"),
    (r"\bFIVB\b", "F.I.V.B."),
    (r"\b5-1\b", "five one"),
    (r"6 vs 6", "6 against 6"),
    (r" · ", ", "),
    (r"\s*—\s*", ", "),
    (r"\.\.\.", ", "),
    (r'"', ""),
    (r"\(([^)]*)\)", r", \1,"),
    (r"\s+,", ","),
    (r",\s*,", ","),
    (r"^,\s*", ""),
    (r",\s*\.", "."),
    (r"\.\s*,", "."),
    (r",\s*:", ":"),
]


def spoken(text):
    for pat, rep in SPOKEN:
        text = re.sub(pat, rep, text)
    # all-caps words read better in normal case (SETTER, KILL, SIDE-OUT ...)
    text = re.sub(r"\b[A-Z][A-Z-]{3,}\b", lambda m: m.group(0).lower(), text)
    return re.sub(r"\s+", " ", text).strip(" ,")


def main():
    voice, speaker = sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else "0"
    lines = json.load(open(os.path.join(HERE, "lines.json")))
    out = os.path.join(HERE, "narr")
    os.makedirs(out, exist_ok=True)
    durations = {}
    for i, scene in enumerate(lines):
        durations[i] = []
        for k, text in enumerate(scene):
            path = os.path.join(out, f"{i}_{k}.wav")
            say = spoken(text)
            subprocess.run([sys.executable, "-m", "piper", "-m", voice, "-s", speaker, "--length-scale", "1.08",
                            "--sentence-silence", "0.25", "-f", path], input=say.encode(), check=True,
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
            with wave.open(path) as w:
                durations[i].append(round(w.getnframes() / w.getframerate(), 2))
            print(f"{i}_{k} {durations[i][-1]:5.2f}s  {say}")
    with open(os.path.join(HERE, "narration.js"), "w") as f:
        f.write("// Generated by narrate.py: spoken length (s) of each caption line, per scene.\n")
        f.write(f"window.NARR = {json.dumps(durations)};\n")


if __name__ == "__main__":
    main()
